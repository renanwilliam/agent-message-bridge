import { readFile } from 'node:fs/promises';
import { SqliteStore } from './sqlite-store.js';
import { Bridge } from './bridge.js';
import { Events } from './events.js';
import { Worker } from './worker.js';
import { createApp } from './app.js';
import { parsePrivateConfig,configuredWebhookRecipients,env } from './config.js';
import { createOAuthAppConfig } from './auth-runtime.js';
import { validateInstallationConfig } from './installation.js';
import { outboundPost } from './transport.js';
import { httpServer,listen,close } from './http.js';
const config=parsePrivateConfig(await readFile(env('BRIDGE_CONFIG_FILE'),'utf8'));
if(process.env.INSTALLATION_ID)validateInstallationConfig(config,process.env.INSTALLATION_ID);
const store=new SqliteStore(env('BRIDGE_DB_FILE'));
const bridge=new Bridge(store,{...config.limits,webhookRecipients:configuredWebhookRecipients(config)});
const app=createApp(bridge,new Events(store,outboundPost),createOAuthAppConfig(config,process.env));
const worker=new Worker(store,{routes:config.routes,leaseMs:30000,retryMs:5000,maxAttempts:config.limits.maxAttempts,responseWaitMs:config.limits.claimMs},outboundPost);
const server=httpServer(app);console.log(`Local bridge listening at ${await listen(server,Number(process.env.PORT??8787))}`);
const timer=setInterval(()=>void worker.drain().catch(()=>console.error('Delivery retry scheduled')),1000);
process.once('SIGINT',async()=>{clearInterval(timer);await close(server);store.close();});
